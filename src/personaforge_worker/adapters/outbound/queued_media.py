import asyncio
from dataclasses import dataclass

from personaforge_worker.domain.media import CanonicalAudioChunk, TimedVideoFrame


@dataclass(slots=True)
class AudioDelivery:
    frame: CanonicalAudioChunk
    delivered: asyncio.Future[None]


@dataclass(slots=True)
class VideoDelivery:
    frame: TimedVideoFrame
    delivered: asyncio.Future[None]


class QueuedMediaPublisher:
    """Bridge the application media pipeline to one clocked LiveKit publishing loop.

    A publish call completes only after the LiveKit loop acknowledges the frame. This
    makes ``PlaybackCompleted`` describe media delivered to the SDK rather than media
    merely generated by the fake TTS/lip-sync runtimes.
    """

    def __init__(self) -> None:
        self._audio: asyncio.Queue[AudioDelivery] = asyncio.Queue(maxsize=1)
        self._video: asyncio.Queue[VideoDelivery] = asyncio.Queue(maxsize=1)
        self._closed = False
        self._error: BaseException | None = None

    async def publish_audio(self, frame: CanonicalAudioChunk) -> None:
        delivery = AudioDelivery(frame, _delivery_future())
        self._assert_open()
        await self._audio.put(delivery)
        await delivery.delivered

    async def publish_video(self, frame: TimedVideoFrame) -> None:
        delivery = VideoDelivery(frame, _delivery_future())
        self._assert_open()
        await self._video.put(delivery)
        await delivery.delivered

    def pop_audio(self) -> AudioDelivery | None:
        try:
            return self._audio.get_nowait()
        except asyncio.QueueEmpty:
            return None

    def pop_video(self) -> VideoDelivery | None:
        try:
            return self._video.get_nowait()
        except asyncio.QueueEmpty:
            return None

    async def close(self) -> None:
        self._closed = True

    def abort(self, error: BaseException) -> None:
        self._closed = True
        self._error = error
        self._reject_pending(self._audio, error)
        self._reject_pending(self._video, error)

    def _assert_open(self) -> None:
        if self._closed:
            raise RuntimeError("LiveKit media publisher is closed") from self._error

    @staticmethod
    def _reject_pending(
        queue: asyncio.Queue[AudioDelivery] | asyncio.Queue[VideoDelivery],
        error: BaseException,
    ) -> None:
        while True:
            try:
                delivery = queue.get_nowait()
            except asyncio.QueueEmpty:
                return
            if not delivery.delivered.done():
                delivery.delivered.set_exception(error)


def acknowledge(delivery: AudioDelivery | VideoDelivery) -> None:
    if not delivery.delivered.done():
        delivery.delivered.set_result(None)


def reject(delivery: AudioDelivery | VideoDelivery, error: BaseException) -> None:
    if not delivery.delivered.done():
        delivery.delivered.set_exception(error)


def _delivery_future() -> asyncio.Future[None]:
    return asyncio.get_running_loop().create_future()
